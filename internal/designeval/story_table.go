// This file renders a test module's Story table: the source file of the
// module's design that declares one scenario per finished flow of a Story, so
// every generation of the module, whoever runs it, requires those tests.
package designeval

import (
	"errors"
	"fmt"
	"go/build"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"io/fs"
	"maps"
	"path"
	"slices"
	"strconv"
	"strings"
)

// StoryTestsPath is the module-relative path of a test module's Story table.
// Surla writes it when a build starts and at each report of the test writer
// (internal/testwriter), and surla init writes the starter's; the module's
// own generation then compiles it with the rest of design/.
const StoryTestsPath = "design/story_tests.go"

// storyTestsHeader starts every Story table. It follows Go's convention for
// generated files and says where the rows come from.
const storyTestsHeader = `// Code generated by surla from the Story's finished flows. DO NOT EDIT.

// This file declares one scenario of this module's evaluation suite per
// finished flow of the project's Story, each run by the method of the same
// name on the acceptance package's Hooks. Regenerating the module keeps them.
`

// ErrDesignPackage reports that StoryTests could not name the Go package of
// the test module's design/ folder, which the Story table must join: no Go
// file of the folder matches the build, one could not be read or parsed, or
// two declare different packages. The cause is in the module's files.
var ErrDesignPackage = errors.New("the test module's design package could not be named")

// StoryTests returns the Story table of the test module whose files module
// holds (rooted at the module's folder, as os.Root.FS or os.DirFS give it), and
// the scenarios it requires, in declaration order: one per complete flow of
// stories, named as StoryScenarios names them. The table is
// story_scenarios.go's evaluation root, in the package the module's other
// design/*.go files declare, registered with one row per scenario; with no
// complete flow it registers no row, and still requires the design to declare
// exactly one evaluation suite.
//
// It reads only the package clauses of design/*.go, never StoryTestsPath
// itself, and writes nothing. An error names two complete flows that map to
// the same scenario or hook, or a flow whose key maps to an empty name (as
// StoryScenarios does), or wraps ErrDesignPackage.
func StoryTests(module fs.FS, stories []StorySummary) ([]byte, []StoryScenario, error) {
	included, _, specs, err := mapStoryFlows(stories)
	if err != nil {
		return nil, nil, err
	}
	pkg, err := designPackage(module)
	if err != nil {
		return nil, nil, fmt.Errorf("%w: %w", ErrDesignPackage, err)
	}
	_, adapter, ok := strings.Cut(storyScenariosSource, "\npackage designeval\n")
	if !ok {
		panic("story_scenarios.go has no package designeval clause")
	}
	var b strings.Builder
	b.WriteString(storyTestsHeader)
	// The blank line keeps the header from becoming the package's doc.
	fmt.Fprintf(&b, "\npackage %s\n%s\n", pkg, adapter)
	b.WriteString("// init registers the Story table's root with one row per finished flow.\n")
	b.WriteString("func init() {\n\tif err := eval.Register(&storyScenarioRoot{scenarios: []storyScenarioSpec{\n")
	for _, sc := range specs {
		fmt.Fprintf(&b, "\t\t{name: %s, description: %s},\n", strconv.Quote(sc.name), strconv.Quote(sc.description))
	}
	b.WriteString("\t}}); err != nil {\n\t\tpanic(err)\n\t}\n}\n")
	table, err := format.Source([]byte(b.String()))
	if err != nil {
		// Every part is fixed source or a quoted literal, so this is a
		// defect of this function, not of the module.
		panic(fmt.Sprintf("format the Story table: %v", err))
	}
	return table, included, nil
}

// designPackage returns the package name the module's design/*.go files
// declare, other than the Story table itself and test files. Only files the
// evaluator's build compiles count: build constraints and file name suffixes
// are matched for the host's GOOS and GOARCH with cgo off, as the sandboxed
// build runs, so a file kept out of the build (such as one tagged ignore) may
// declare another package.
func designPackage(module fs.FS) (string, error) {
	entries, err := fs.ReadDir(module, "design")
	if err != nil {
		return "", err
	}
	ctxt := build.Default
	ctxt.CgoEnabled = false
	ctxt.JoinPath = path.Join
	ctxt.OpenFile = func(name string) (io.ReadCloser, error) { return module.Open(name) }
	found := map[string]string{}
	for _, e := range entries {
		name := e.Name()
		file := path.Join("design", name)
		if !e.Type().IsRegular() || file == StoryTestsPath || strings.HasSuffix(name, "_test.go") {
			continue
		}
		match, err := ctxt.MatchFile("design", name)
		if err != nil {
			return "", err
		}
		if !match {
			continue
		}
		src, err := fs.ReadFile(module, file)
		if err != nil {
			return "", err
		}
		parsed, err := parser.ParseFile(token.NewFileSet(), file, src, parser.PackageClauseOnly)
		if err != nil {
			return "", err
		}
		found[parsed.Name.Name] = file
	}
	switch names := slices.Sorted(maps.Keys(found)); len(names) {
	case 0:
		return "", errors.New("design/ holds no Go file that declares the design package")
	case 1:
		return names[0], nil
	default:
		return "", fmt.Errorf("design/ declares packages %s (%s) and %s (%s)",
			names[0], found[names[0]], names[1], found[names[1]])
	}
}
